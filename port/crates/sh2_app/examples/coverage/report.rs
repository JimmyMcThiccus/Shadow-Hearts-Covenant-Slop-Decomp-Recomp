pub fn write(out: &Path, md: &Path) {
    let mut s = String::new();
    let now = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0);
    let _ = writeln!(s, "# Whole-game coverage matrix (round 5 QA)\n");
    let _ = writeln!(
        s,
        "Generated by `tools/coverage/run_all.ps1` (= `cargo run --release -p sh2_app --example coverage -- all`, resumable; `--fresh` reruns everything; one category: `... -- run field`; regenerate this file from the raw rows: `... -- report`).  Raw rows: `tools/coverage/out/<category>.tsv`.  Disc: US retail `SH2_US_DISC_DIR`.  Generated at unix time {now}.\n"
    );
    let _ = writeln!(s, "Status: **ok** = runs to the end with nothing missing; **stub** = runs but hits unimplemented / placeholder code (listed); **fails** = panic / load error; **timeout** = hangs; **untested** = could not be checked headless.  Owner = the agent of the file to fix (round5_brief.md).\n");
    // totals
    let _ = writeln!(s, "## Totals\n\n| category | items | ok | stub | fails | timeout | untested |\n|---|---|---|---|---|---|---|");
    let mut all: BTreeMap<&str, Vec<Row>> = BTreeMap::new();
    let mut tot = [0usize; 6];
    for c in CATS {
        let rows = dedup(cat_files(out, c.key).iter().flat_map(|f| read_rows(f)).collect());
        let n = |st: &str| rows.iter().filter(|r| r.status == st).count();
        let v = [rows.len(), n("ok"), n("stub"), n("fails"), n("timeout"), n("untested")];
        for i in 0..6 {
            tot[i] += v[i];
        }
        let _ = writeln!(s, "| [{}](#{}) | {} | {} | {} | {} | {} | {} |", c.title, anchor(c.title), v[0], v[1], v[2], v[3], v[4], v[5]);
        all.insert(c.key, rows);
    }
    let _ = writeln!(s, "| **all** | {} | {} | {} | {} | {} | {} |\n", tot[0], tot[1], tot[2], tot[3], tot[4], tot[5]);
    // per owner
    let mut by_owner: BTreeMap<String, [usize; 3]> = BTreeMap::new();
    for rows in all.values() {
        for r in rows.iter().filter(|r| r.status != "ok") {
            for o in r.owner.split('/').filter(|o| !o.is_empty()) {
                let e = by_owner.entry(o.to_string()).or_default();
                match r.status.as_str() {
                    "fails" | "timeout" => e[0] += 1,
                    "stub" => e[1] += 1,
                    _ => e[2] += 1,
                }
            }
        }
    }
    let _ = writeln!(s, "Open items per owner (an item can name several owners):\n\n| owner | fails + timeout | stub | untested |\n|---|---|---|---|");
    for (o, v) in &by_owner {
        let _ = writeln!(s, "| {o} | {} | {} | {} |", v[0], v[1], v[2]);
    }
    s.push('\n');
    // hand-written analysis
    if let Ok(notes) = std::fs::read_to_string(super::root().join("tools/coverage/notes.md")) {
        s.push_str(&notes);
        s.push('\n');
    }
    for c in CATS {
        let rows = &all[c.key];
        let _ = writeln!(s, "## {}\n\n{}.\n", c.title, c.what);
        if rows.is_empty() {
            let _ = writeln!(s, "_not run yet_\n");
            continue;
        }
        // aggregates
        for (key, label) in c.agg {
            let mut m: BTreeMap<String, (usize, String)> = BTreeMap::new();
            for r in rows {
                if let Some(v) = r.get(key) {
                    for it in v.split(',').filter(|x| !x.is_empty()) {
                        let e = m.entry(it.to_string()).or_insert((0, r.owner.clone()));
                        e.0 += 1;
                    }
                }
            }
            if m.is_empty() {
                continue;
            }
            let mut v: Vec<(String, (usize, String))> = m.into_iter().collect();
            v.sort_by(|a, b| b.1 .0.cmp(&a.1 .0));
            let _ = writeln!(s, "**{label}** (items affected):\n");
            let names: Vec<String> = v.iter().map(|(k, (n, _))| format!("`{}` {n}", pretty(c.key, key, k))).collect();
            let _ = writeln!(s, "{}\n", names.join(", "));
        }
        // failures first
        let mut sorted: Vec<&Row> = rows.iter().collect();
        let rank = |st: &str| match st {
            "fails" => 0,
            "timeout" => 1,
            "stub" => 2,
            "untested" => 3,
            _ => 4,
        };
        sorted.sort_by(|a, b| rank(&a.status).cmp(&rank(&b.status)).then(a.id.cmp(&b.id)));
        let _ = writeln!(s, "| item | status | failing op / panic / missing | owner |\n|---|---|---|---|");
        for r in sorted {
            let d: String = r.detail.replace('|', "\\|").chars().take(400).collect();
            let id = match (c.key, r.get("disc")) {
                ("lsd", Some(dk)) => format!("{} ({dk})", r.id),
                _ => r.id.clone(),
            };
            let _ = writeln!(s, "| {} | {} | {} | {} |", id, r.status, d, if r.status == "ok" { "" } else { &r.owner });
        }
        s.push('\n');
    }
    std::fs::write(md, s).unwrap();
    eprintln!("coverage: wrote {}", md.display());
}

fn dedup(rows: Vec<Row>) -> Vec<Row> {
    // a resumed run can have a timeout row followed by nothing, or two rows for an id: keep the last
    let mut m: BTreeMap<String, Row> = BTreeMap::new();
    for r in rows {
        m.insert(r.id.clone(), r);
    }
    m.into_values().collect()
}

fn anchor(t: &str) -> String {
    t.to_lowercase().replace(' ', "-").replace('/', "")
}

fn pretty(cat: &str, key: &str, v: &str) -> String {
    if cat == "field" && key == "unimpl" {
        if let Some((e, sub)) = v.split_once('.') {
            if let (Ok(e), Ok(sub)) = (u8::from_str_radix(e, 16), u8::from_str_radix(sub, 16)) {
                return format!("{} [{}]", field_op_name(e, sub), field_op_owner(e, sub));
            }
        }
    }
    v.to_string()
}
